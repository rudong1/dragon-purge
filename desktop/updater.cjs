'use strict';

const STARTUP_DELAY_MS = 10_000;
const CHECK_INTERVAL_MS = 6 * 60 * 60 * 1000;

function updateErrorMessage(error) {
  const code = String(error?.code || '');
  if (/CHECKSUM|SHA512|SHA256|SIGNATURE|INVALID_SIGNATURE/i.test(code)) {
    return '更新文件未通过校验，已停止安装，请稍后重试。';
  }
  if (/LATEST_VERSION_NOT_FOUND|CHANNEL_FILE_NOT_FOUND|404/i.test(code) || /\b404\b/.test(String(error?.message || ''))) {
    return '暂未找到已发布的更新版本，稍后会自动重试。';
  }
  return '更新检查或下载失败，请检查网络后重试。';
}

function displayVersion(value) {
  return typeof value === 'string' ? value.replace(/[\x00-\x1f\x7f]/g, '').slice(0, 64) : undefined;
}

/**
 * Installed Windows builds use the GitHub feed generated by electron-builder.
 * Dependencies and timers may be injected to validate the update lifecycle
 * without loading Electron or contacting the release service in tests.
 */
function createUpdater({
  app,
  onStatus = () => {},
  platform = process.platform,
  updater: suppliedUpdater,
  loadUpdater = () => require('electron-updater').autoUpdater,
  setTimeout: later = global.setTimeout,
  clearTimeout: clearLater = global.clearTimeout,
  setInterval: every = global.setInterval,
  clearInterval: clearEvery = global.clearInterval,
} = {}) {
  let state = {
    enabled: Boolean(app?.isPackaged && platform === 'win32'),
    phase: 'idle',
    currentVersion: displayVersion(app?.getVersion?.()) || '0.0.0',
    message: '会自动检查并下载更新，安装后可在菜单中选择重启。',
  };
  let disposed = false;
  let inFlight = null;
  let manualCheck = false;
  let startupTimer;
  let repeatTimer;
  let updater;
  const listeners = [];

  function publish(next) {
    if (disposed) return;
    state = {
      enabled: state.enabled,
      currentVersion: state.currentVersion,
      manual: manualCheck,
      ...next,
    };
    onStatus({ ...state });
  }

  function getState() {
    return { ...state };
  }

  function failure(error) {
    publish({ phase: 'error', message: updateErrorMessage(error) });
  }

  async function checkForUpdates({ manual = false } = {}) {
    if (disposed || !state.enabled) return getState();
    if (inFlight) return inFlight;
    // An available update is automatically downloading. Never start another
    // check while a download is active or an installable update is waiting.
    if (['available', 'downloading', 'downloaded'].includes(state.phase)) return getState();
    manualCheck = Boolean(manual);
    publish({ phase: 'checking', message: '正在检查新版本…' });
    inFlight = Promise.resolve()
      .then(() => updater.checkForUpdates())
      .catch(failure)
      .then(getState)
      .finally(() => { inFlight = null; });
    return inFlight;
  }

  function quitAndInstall() {
    if (disposed || !state.enabled || state.phase !== 'downloaded') return false;
    try {
      // This method is called only by an explicit menu/button action. Updates
      // never close the desktop pet or restart the computer on their own.
      updater.quitAndInstall(false, true);
      return true;
    } catch (error) {
      failure(error);
      return false;
    }
  }

  function listen(name, handler) {
    updater.on(name, handler);
    listeners.push([name, handler]);
  }

  function dispose() {
    if (disposed) return;
    disposed = true;
    if (startupTimer !== undefined) clearLater(startupTimer);
    if (repeatTimer !== undefined) clearEvery(repeatTimer);
    for (const [name, handler] of listeners) updater?.removeListener(name, handler);
    app?.removeListener?.('before-quit', dispose);
  }

  const api = { checkForUpdates, quitAndInstall, dispose, getState };

  if (!state.enabled) {
    publish({
      phase: 'disabled',
      message: !app?.isPackaged
        ? '开发模式未启用自动更新；安装 Windows 发布版后会自动检查。'
        : '当前平台暂未启用自动更新，请从 GitHub Releases 安装新版本。',
    });
    return api;
  }

  try {
    updater = suppliedUpdater || loadUpdater();
    updater.autoDownload = true;
    updater.autoInstallOnAppQuit = false;
    updater.allowDowngrade = false;
    updater.allowPrerelease = false;
    listen('checking-for-update', () => publish({ phase: 'checking', message: '正在检查新版本…' }));
    listen('update-available', (info) => publish({
      phase: 'available',
      version: displayVersion(info?.version),
      message: '发现新版本，正在后台下载…',
    }));
    listen('download-progress', (progress) => publish({
      phase: 'downloading',
      version: state.version,
      percent: Math.max(0, Math.min(100, Number(progress?.percent) || 0)),
      message: '正在后台下载更新…',
    }));
    listen('update-downloaded', (info) => publish({
      phase: 'downloaded',
      version: displayVersion(info?.version),
      percent: 100,
      message: '新版本已下载；在菜单中选择“安装更新并重启”即可安装。',
    }));
    listen('update-not-available', () => publish({ phase: 'up-to-date', message: '当前已是最新版本。' }));
    listen('error', failure);
    startupTimer = later(() => { void checkForUpdates(); }, STARTUP_DELAY_MS);
    repeatTimer = every(() => { void checkForUpdates(); }, CHECK_INTERVAL_MS);
    startupTimer?.unref?.();
    repeatTimer?.unref?.();
    app?.once?.('before-quit', dispose);
    onStatus(getState());
  } catch {
    state.enabled = false;
    publish({ phase: 'error', message: '更新组件暂不可用，请从 GitHub Releases 安装最新版本。' });
  }
  return api;
}

module.exports = { createUpdater, updateErrorMessage, STARTUP_DELAY_MS, CHECK_INTERVAL_MS };
